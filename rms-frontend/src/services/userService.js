import api from './api'


const userService = {


    /*
    |--------------------------------------------------------------------------
    | User List
    |--------------------------------------------------------------------------
    */

    getUsers(params = {})
    {
        return api.get(
            '/admin/users',
            {
                params
            }
        )
    },


    /*
    |--------------------------------------------------------------------------
    | Single User
    |--------------------------------------------------------------------------
    */

    getUser(id)
    {
        return api.get(
            `/admin/users/${id}`
        )
    },


    /*
    |--------------------------------------------------------------------------
    | Update User
    |--------------------------------------------------------------------------
    */

    updateUser(
        id,
        data
    )
    {
        return api.put(
            `/admin/users/${id}`,
            data
        )
    },
    /*
|--------------------------------------------------------------------------
| Roles
|--------------------------------------------------------------------------
*/

getRoles()
{
    return api.get(
        '/admin/users/roles'
    )
},
/*
|--------------------------------------------------------------------------
| Create User
|--------------------------------------------------------------------------
*/

createUser(data)
{
    return api.post(
        '/admin/users',
        data,
        {
            headers:{
                'Content-Type':
                'multipart/form-data'
            }
        }
    )
},

    /*
    |--------------------------------------------------------------------------
    | Delete User
    |--------------------------------------------------------------------------
    */

    deleteUser(id)
    {
        return api.delete(
            `/admin/users/${id}`
        )
    },


    /*
    |--------------------------------------------------------------------------
    | Block / Unblock
    |--------------------------------------------------------------------------
    */

    toggleStatus(
        id,
        isActive
    )
    {
        return api.patch(
            `/admin/users/${id}/status`,
            {
                is_active:
                    isActive
            }
        )
    },


}


export default userService